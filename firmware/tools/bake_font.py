#!/usr/bin/env python3
"""bake_font.py - bake the Inter Bold face into 4-bpp C masks.

Source: app/Sources/Cue9App/Resources/InterVariable.ttf (OFL). Requires Pillow.
Output: firmware/src/font_baked.c (+ font_baked.h), then copy both into
app/Sources/Cue9Preview/ so the app's preview renderer stays in step.

  python3 firmware/tools/bake_font.py [--sizes 10,14,18,22,64]

Per glyph: tight mask, integer advance, bearing relative to the pen/baseline.
4 bpp: two pixels per byte, high nibble = left pixel. Space has no mask.
Beyond printable ASCII the face carries U+2026 (ellipsis), U+00B0 (degree)
and U+00B7 (middle dot); r_text passes those codepoints through as glyph ids.
"""
import argparse
import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "app/Sources/Cue9App/Resources/InterVariable.ttf")
OUT_C = os.path.join(ROOT, "firmware/src/font_baked.c")
OUT_H = os.path.join(ROOT, "firmware/src/font_baked.h")
PAD = 16
SIZES = [10, 14, 18, 22, 64]
WEIGHT = "Bold"
CPS = list(range(32, 127)) + [0x2026, 0x00B0, 0x00B7]   # 98 glyphs
GID = {cp: i for i, cp in enumerate(CPS)}


def mask_for(font, ch):
    """Return (w,h,adv,bx,by,4bpp bytes) for one glyph, or a blank."""
    adv = int(round(font.getlength(ch)))
    canvas = Image.new("L", (max(adv, font.size) + 4 * PAD, 4 * font.size + 4 * PAD), 0)
    d = ImageDraw.Draw(canvas)
    base = 2 * font.size + PAD
    d.text((2 * PAD, base), ch, font=font, fill=255, anchor="ls")
    box = canvas.getbbox()
    if box is None:
        return 0, 0, adv, 0, 0, b""
    x0, y0, x1, y1 = box
    im = canvas.crop(box)
    w, h = im.size
    # tight crop: bx/by are from the pen origin / baseline
    bx = x0 - 2 * PAD
    by = y0 - base
    stride = (w + 1) // 2
    out = bytearray(stride * h)
    px = im.load()
    for y in range(h):
        for x in range(w):
            q = (px[x, y] * 15 + 127) // 255
            if q:
                out[y * stride + x // 2] |= (q << 4) if (x & 1) == 0 else q
    return w, h, adv, bx, by, bytes(out)


def bake_size(size):
    font = ImageFont.truetype(SRC, size)
    try:
        font.set_variation_by_name(WEIGHT)
    except Exception as exc:  # pragma: no cover
        raise SystemExit(f"cannot select {WEIGHT}: {exc}")
    ascent, descent = font.getmetrics()
    cap = font.getbbox("H", anchor="ls")[3] - font.getbbox("H", anchor="ls")[1]
    metas, blob = [], bytearray()
    for cp in CPS:
        ch = chr(cp)
        w, h, adv, bx, by, data = mask_for(font, ch)
        metas.append((w, h, adv, bx, by, len(blob)))
        blob += data
    return dict(size=size, ascent=ascent, descent=descent, cap=cap,
                metas=metas, blob=blob)


def c_bytes(data):
    lines = []
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--sizes", default=",".join(str(s) for s in SIZES))
    args = ap.parse_args()
    sizes = [int(s) for s in args.sizes.split(",") if s.strip()]
    faces = [bake_size(s) for s in sizes]

    total = sum(len(f["blob"]) for f in faces)
    print(f"baking {len(faces)} faces, {len(CPS)} glyphs, {total} mask bytes")

    parts = [
        "/* font_baked.c - generated by firmware/tools/bake_font.py; do not edit.\n"
        " * Source: Inter Variable (OFL), weight Bold, 4-bpp masks. */\n"
        '#include "font_baked.h"\n'
    ]
    for i, face in enumerate(faces):
        parts.append(f"static const uint8_t mask{i}[] = {{\n{c_bytes(face['blob'])}\n}};\n")
        rows = ",\n".join(
            "  {%d, %d, %d, %d, %d, %d}" % m for m in face["metas"]
        )
        parts.append(f"static const r_font_glyph_meta meta{i}[] = {{\n{rows},\n}};\n")
    rows = ",\n".join(
        "  {%d, %d, %d, %d, %d, meta%d, mask%d}"
        % (f["size"], f["ascent"], f["descent"], f["cap"], len(CPS), i, i)
        for i, f in enumerate(faces)
    )
    parts.append(
        "const r_font_face r_font_faces[R_FONT_NFACE] = {\n%s,\n};\n" % rows
    )
    with open(OUT_C, "w", encoding="utf-8") as fh:
        fh.write("\n".join(parts))

    with open(OUT_H, "w", encoding="utf-8") as fh:
        fh.write(
            "/* font_baked.h - generated by firmware/tools/bake_font.py; do not edit. */\n"
            "#ifndef FONT_BAKED_H\n"
            "#define FONT_BAKED_H\n\n"
            "#include <stdint.h>\n\n"
            "/* off is a byte offset into the face mask blob. */\n"
            "typedef struct { uint8_t w, h, adv; int8_t bx, by; uint32_t off; } r_font_glyph_meta;\n"
            "typedef struct { uint8_t size, ascent, descent, cap; uint16_t nglyph;\n"
            "                     const r_font_glyph_meta *meta; const uint8_t *mask; } r_font_face;\n\n"
            f"#define R_FONT_NFACE {len(faces)}\n"
            "extern const r_font_face r_font_faces[R_FONT_NFACE];\n\n"
            "#endif\n"
        )
    print(f"wrote {OUT_C} and {OUT_H}")


if __name__ == "__main__":
    main()
